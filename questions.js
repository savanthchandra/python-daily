// Normalize any legacy or handbook topic name to one of the 13 canonical topics
function normalizeTopic(rawTopic, chapter) {
  if (!rawTopic && chapter) {
    const byCh = TOPIC_META.find((t) => t.chapter === Number(chapter));
    if (byCh) return byCh.name;
  }
  const s = String(rawTopic || "").toLowerCase();
  if (s.includes("module") || s.includes("pip") || s.includes("comment")) return "Modules & pip";
  if (s.includes("operator") || s.includes("type") || s.includes("variable") || s.includes("arithmetic")) return "Variables & Operators";
  if (s.includes("string") || s.includes("slic")) return "Strings & Slicing";
  if (s.includes("list") || s.includes("tuple") || s.includes("mutab")) return "Lists & Tuples";
  if (s.includes("dict") || s.includes("set")) return "Dictionaries & Sets";
  if (s.includes("condition") || s.includes("logic") || s.includes("short circuit") || s.includes("bool")) return "Conditions & Logic";
  if (s.includes("loop") || s.includes("range") || s.includes("iter")) return "Loops & Iteration";
  if (s.includes("function") || s.includes("scope") || s.includes("arg") || s.includes("return") || s.includes("default") || s.includes("closure") || s.includes("recurs")) return "Functions & Scope";
  if (s.includes("file") || s.includes("with")) return "File I/O";
  if (s.includes("class") || s.includes("oop") || s.includes("self") || s.includes("init")) return "OOP & Classes";
  if (s.includes("inherit") || s.includes("dunder") || s.includes("property") || s.includes("super") || s.includes("classmethod")) return "Inheritance & Dunders";
  if (s.includes("except") || s.includes("comprehen") || s.includes("enumerate") || s.includes("try")) return "Exceptions & Comprehensions";
  if (s.includes("functional") || s.includes("lambda") || s.includes("map") || s.includes("filter") || s.includes("typing") || s.includes("venv")) return "Functional & Typing";
  if (chapter) {
    const byCh = TOPIC_META.find((t) => t.chapter === Number(chapter));
    if (byCh) return byCh.name;
  }
  return "Lists & Tuples";
}

function makeMcq(id, level, chapter, topic, code, answer, wrongOptions, why, hint, source) {
  const defaultSource =
    level === 0
      ? `Python 3 Docs · Ch ${String(chapter).padStart(2, "0")} Core Reference`
      : level === 1
      ? `Python 3 Standard Library & Idioms`
      : `CPython Internals & Interview Gotchas`;
  return {
    id,
    level, // 0 = Easy, 1 = Medium, 2 = Hard
    chapter,
    topic: normalizeTopic(topic, chapter),
    code,
    answer: String(answer),
    options: [String(answer), ...wrongOptions.map(String)],
    why,
    hint,
    source: source || defaultSource,
  };
}

